import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { parseDirectoryListing, looksLikeDirectoryListing, isSafeEntryName, MAX_LISTING_ROWS } from "../lib/listing.js";

const realPage = readFileSync(new URL("./fixtures/listing-history.html", import.meta.url), "utf8");
const row = (name, isDir = 0, size = 10, mtime = 1795101154) =>
  `<script>addRow(${JSON.stringify(name)},${JSON.stringify(encodeURIComponent(name))},${isDir},${size},"10 B",${mtime},"11/19/26, 10:12:34 AM");</script>`;

test("reads every entry of a listing page generated by real Chrome 157", () => {
  const entries = parseDirectoryListing(realPage);
  assert.deepEqual(entries.map((e) => e.name), ["1777000000.run", "1777003600.run", "1777003600.run.backup", "notes.txt"]);
  assert.deepEqual(entries[0], { name: "1777000000.run", isDir: false, size: 2587, mtime: 1795101154 });
});

test("recognizes a listing page, and does not mistake the page's own script for rows", () => {
  assert.equal(looksLikeDirectoryListing(realPage), true);
  assert.equal(looksLikeDirectoryListing('{"seed":"ABC"}'), false);
  const emptyFolder = realPage.replace(/<script>addRow\(".*\n?/g, "");
  assert.equal(looksLikeDirectoryListing(emptyFolder), true);
  assert.deepEqual(parseDirectoryListing(emptyFolder), []);
});

test("marks folders and keeps sizes and times as numbers", () => {
  const entries = parseDirectoryListing(row("profile1", 1, 0, 1700000000) + row("a.run", 0, 21405, 1700000001));
  assert.deepEqual(entries, [
    { name: "profile1", isDir: true, size: 0, mtime: 1700000000 },
    { name: "a.run", isDir: false, size: 21405, mtime: 1700000001 },
  ]);
});

test("decodes names the way Chromium escapes them", () => {
  const page = '<script>addRow("he said \\"hi\\".run","x",0,1,"1 B",2,"d");</script>'
    + '<script>addRow("a\\u003Cb.run","x",0,1,"1 B",2,"d");</script>';
  assert.deepEqual(parseDirectoryListing(page).map((e) => e.name), ['he said "hi".run', "a<b.run"]);
});

test("drops names that could step outside the folder", () => {
  const page = [row(".."), row("."), row(".. "), row("..."), row("a/b.run"), row("a\\b.run"), row("ok.run"), row("bad\u0001.run")].join("");
  assert.deepEqual(parseDirectoryListing(page).map((e) => e.name), ["ok.run"]);
  assert.equal(isSafeEntryName(""), false);
  assert.equal(isSafeEntryName("x".repeat(256)), false);
  assert.equal(isSafeEntryName("Application Support"), true);
  assert.equal(isSafeEntryName(".local"), true);
  assert.equal(isSafeEntryName("half\ud800pair"), false, "cannot be written into a URL");
});

test("returns nothing for input that is not a listing or is absurdly large", () => {
  assert.deepEqual(parseDirectoryListing(""), []);
  assert.deepEqual(parseDirectoryListing(null), []);
  assert.deepEqual(parseDirectoryListing("x".repeat(8 * 1024 * 1024 + 1)), []);
  assert.deepEqual(parseDirectoryListing('addRow("a.run","a.run",2,1,"1 B",2,"d");'), []);
});

test("stops at the row limit", () => {
  const page = Array.from({ length: MAX_LISTING_ROWS + 5 }, (_, i) => row(`${i}.run`)).join("");
  assert.equal(parseDirectoryListing(page).length, MAX_LISTING_ROWS);
});
