#!/usr/bin/env node
/**
 * Builds the painted sprites that bring the header's scenes to life (the
 * new look), from the masters in scripts/stage-art/life/:
 *
 *   clouds that drift across a sky (pink above the clouds, night blue over
 *   the mountains, volcanic ash over the wastes), a crow and a bat that
 *   cross now and then, a maple leaf and a jungle leaf that fall, a
 *   lightning bolt, a ghost wisp, and a floating islet.
 *
 * Each master is cropped to its art (boxes measured on the masters, in
 * master pixels) and written once at about twice the largest size the
 * header draws it, so it stays sharp on a 2x screen:
 *
 *   Web/assets/stage/life/<id>-v<version>.webp
 *   Web/lib/ui/stage-life-sprites.js   each sprite's file and size
 *
 * Where each scene uses them, and how they move: Web/lib/ui/stage-life-list.js.
 *
 * The masters were generated with GPT Image 2.6 (Higgsfield), 2k,
 * transparent background, quality high; prompts in scripts/stage-art/README.md.
 *
 *   node scripts/build-stage-life.mjs
 *
 * Needs `cwebp` (Homebrew: brew install webp). Bump a sprite's `version`
 * when its master or crop changes: /assets is cached as immutable.
 */

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const MASTERS = join(REPO_ROOT, "scripts", "stage-art", "life");
const OUT_DIR = join(REPO_ROOT, "Web", "assets", "stage", "life");
const MODULE = join(REPO_ROOT, "Web", "lib", "ui", "stage-life-sprites.js");

/**
 * crop: the art's box in the master (x, y, w, h), a few pixels of air kept
 * round it. size: [width, 0] or [0, height] of the built picture, in px.
 */
const SPRITES = Object.freeze([
  { id: "cloud-pink", version: 1, crop: [8, 448, 2023, 478], size: [1100, 0] },
  { id: "cloud-night", version: 1, crop: [28, 510, 1994, 371], size: [1100, 0] },
  { id: "cloud-ash", version: 1, crop: [39, 112, 1975, 1174], size: [900, 0] },
  { id: "crow", version: 1, crop: [78, 2, 1871, 1354], size: [140, 0] },
  { id: "bat", version: 1, crop: [11, 374, 2026, 652], size: [140, 0] },
  { id: "leaf-red", version: 1, crop: [50, 26, 1948, 2006], size: [72, 0] },
  { id: "leaf-green", version: 1, crop: [86, 237, 1906, 1640], size: [72, 0] },
  { id: "bolt", version: 1, crop: [282, 14, 744, 2020], size: [0, 460] },
  { id: "wisp", version: 1, crop: [321, 62, 712, 1902], size: [0, 180] },
  { id: "islet", version: 1, crop: [219, 10, 1607, 2024], size: [320, 0] },
]);

function fail(message) {
  process.stderr.write(`build-stage-life: ${message}\n`);
  process.exit(1);
}

/** @param {string} path */
function pixelSize(path) {
  const out = execFileSync("sips", ["-g", "pixelWidth", "-g", "pixelHeight", path], { encoding: "utf8" });
  const width = Number(/pixelWidth: (\d+)/.exec(out)?.[1]);
  const height = Number(/pixelHeight: (\d+)/.exec(out)?.[1]);
  if (!width || !height) fail(`could not read the size of ${path}`);
  return { width, height };
}

/** @param {{ id: string, version: number, crop: number[] | null, size: number[] }} sprite */
function buildSprite(sprite) {
  const master = join(MASTERS, `${sprite.id}.webp`);
  if (!existsSync(master)) fail(`missing master ${master}`);
  const size = pixelSize(master);
  const [x, y, w, h] = sprite.crop || [0, 0, size.width, size.height];
  if (x < 0 || y < 0 || x + w > size.width || y + h > size.height) fail(`${sprite.id}: crop ${sprite.crop} is outside the ${size.width}x${size.height} master`);
  const file = `${sprite.id}-v${sprite.version}.webp`;
  const out = join(OUT_DIR, file);
  execFileSync("cwebp", [
    "-quiet", "-q", "88", "-alpha_q", "100", "-exact", "-m", "6", "-sharp_yuv",
    "-crop", String(x), String(y), String(w), String(h),
    "-resize", String(sprite.size[0]), String(sprite.size[1]),
    master, "-o", out,
  ]);
  const built = pixelSize(out);
  return { id: sprite.id, src: `/assets/stage/life/${file}`, width: built.width, height: built.height };
}

function moduleSource(built) {
  const rows = built.map((s) => `  "${s.id}": Object.freeze({ src: ${JSON.stringify(s.src)}, width: ${s.width}, height: ${s.height} }),`);
  return `// GENERATED by scripts/build-stage-life.mjs — do not edit by hand.
//
// The painted sprites the header's scenes are brought to life with: drifting
// clouds, a crow and a bat, falling leaves, a lightning bolt, a ghost wisp
// and a floating islet. Where each scene uses them: stage-life-list.js.

export const LIFE_SPRITES = Object.freeze({
${rows.join("\n")}
});
`;
}

function main() {
  mkdirSync(OUT_DIR, { recursive: true });
  const built = SPRITES.map(buildSprite);
  writeFileSync(MODULE, moduleSource(built));
  for (const s of built) process.stdout.write(`  ${s.src}  ${s.width}x${s.height}\n`);
  process.stdout.write(`  ${MODULE.replace(`${REPO_ROOT}/`, "")}\n`);
}

main();
