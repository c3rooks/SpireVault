#!/usr/bin/env node
/**
 * Writes the large relic icons (Web/assets/sts2/relics-hd-v1/<slug>.webp) and
 * the list of them (Web/lib/ui/relic-art-hd.js), from the installed game.
 *
 * The shipped relic icons are 128px: sharp in a list, soft wherever the new
 * look shows a relic big (the Top Relics podium draws #1 at 128 CSS px, which
 * is 256 device pixels on a retina screen). The game's own icons are 256px, so
 * this writes them pixel for pixel: no resampling, just decoded and encoded.
 *
 * Every shipped 128px icon is matched to the game icon it was made from, and
 * the game icon is checked against it (scaled down the way the 128px set was
 * framed: 0.48, centred). An icon whose art no longer matches is left out and
 * reported, so a large icon never shows different art from its small one.
 * Relics the game only has as an 85px atlas sprite get no large icon.
 *
 *   node scripts/build-relic-icons-hd.mjs [path/to/Slay the Spire 2.pck] [--dry] [--preview <dir>]
 */

import { chromium } from "playwright";
import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { arg, flag, imageDataUrl, loadImage, openPck, pckPathFromArgs, relicCatalog } from "./sts2-pck/pck.mjs";

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const ASSET_ROOT = join(REPO_ROOT, "Web", "assets", "sts2");
const RELIC_DIR = join(ASSET_ROOT, "relics");
const HD_DIR_NAME = "relics-hd-v1";
const HD_DIR = join(ASSET_ROOT, HD_DIR_NAME);
const MODULE_FILE = join(REPO_ROOT, "Web", "lib", "ui", "relic-art-hd.js");

const HD = Object.freeze({ size: 256, smallSize: 128, smallContentScale: 0.96 });
/** cwebp settings: high quality, alpha kept exactly, sharp colour edges. */
const CWEBP_ARGS = Object.freeze(["-q", "94", "-m", "6", "-alpha_q", "100", "-sharp_yuv", "-exact", "-quiet"]);
/** Mean abs. error (0-255, alpha-weighted RGB + alpha) above which the art is judged different. */
const SAME_ART_MAX_ERROR = 9;

/** The game relic each shipped icon was made from (same rule as relicImageSrc / build-relic-icons). */
function matchShippedIcons(catalog) {
  const bySlug = new Map(catalog.map((relic) => [relic.slug, relic]));
  return readdirSync(RELIC_DIR)
    .filter((file) => file.endsWith(".webp"))
    .map((file) => {
      const shipped = file.slice(0, -".webp".length);
      const flat = shipped.replace(/_/g, "");
      const relic = bySlug.get(flat) ?? (flat.startsWith("the") ? bySlug.get(flat.slice(3)) : undefined);
      return { shipped, relic: relic ?? null };
    });
}

/**
 * Page side: draws the game icon at its own size onto a square canvas (PNG,
 * lossless) and measures how far it is from the shipped small icon.
 */
function renderInPage({ gameUrl, smallUrl, size, smallSize, smallContentScale }) {
  const load = (url) =>
    new Promise((resolve, reject) => {
      const image = new Image();
      image.onload = () => resolve(image);
      image.onerror = () => reject(new Error("image failed to decode"));
      image.src = url;
    });
  const pixels = (source, canvasSize, side) => {
    const canvas = document.createElement("canvas");
    canvas.width = canvasSize;
    canvas.height = canvasSize;
    const ctx = canvas.getContext("2d");
    ctx.imageSmoothingQuality = "high";
    const inset = (canvasSize - side) / 2;
    ctx.drawImage(source, inset, inset, side, side);
    return { canvas, data: ctx.getImageData(0, 0, canvasSize, canvasSize).data };
  };
  return Promise.all([load(gameUrl), load(smallUrl)]).then(([game, small]) => {
    const large = pixels(game, size, size);
    const downscaled = pixels(game, smallSize, smallSize * smallContentScale).data;
    const shipped = pixels(small, smallSize, smallSize).data;
    let error = 0;
    for (let i = 0; i < shipped.length; i += 4) {
      const alpha = Math.max(downscaled[i + 3], shipped[i + 3]) / 255;
      for (let c = 0; c < 3; c++) error += Math.abs(downscaled[i + c] - shipped[i + c]) * alpha;
      error += Math.abs(downscaled[i + 3] - shipped[i + 3]);
    }
    return {
      width: game.naturalWidth,
      height: game.naturalHeight,
      error: error / (shipped.length),
      png: large.canvas.toDataURL("image/png").split(",")[1],
    };
  });
}

/** PNG bytes -> WebP bytes through cwebp. */
function encodeWebp(pngBytes, workDir, slug) {
  const pngPath = join(workDir, `${slug}.png`);
  const webpPath = join(workDir, `${slug}.webp`);
  writeFileSync(pngPath, pngBytes);
  execFileSync("cwebp", [...CWEBP_ARGS, pngPath, "-o", webpPath]);
  return readFileSync(webpPath);
}

function moduleSource(slugs) {
  return `// GENERATED by scripts/build-relic-icons-hd.mjs — do not edit by hand.
//
// The game's relic icons at their own size (${HD.size}px), for wherever the new
// look shows a relic large. The shipped set (/assets/sts2/relics) is ${HD.smallSize}px:
// sharp in a list, soft once a relic is drawn over ~64 CSS px on a retina
// screen. Relics not in \`slugs\` have no large icon and keep the small one.

export const RELIC_ART_HD = Object.freeze({
  dir: "/assets/sts2/${HD_DIR_NAME}",
  size: ${HD.size},
  slugs: Object.freeze(new Set(${JSON.stringify(slugs)})),
});

/**
 * The large icon for a relic image URL from relicImageSrc() (with or without a
 * ?v= token), or the URL itself when there is no large one (or it is not a
 * relic image).
 * @param {string | null} src
 * @returns {string | null}
 */
export function hdRelicSrc(src) {
  const match = src ? /\\/relics\\/([^/?]+)\\.webp(?:\\?.*)?$/.exec(src) : null;
  if (!match || !RELIC_ART_HD.slugs.has(match[1])) return src;
  return \`\${RELIC_ART_HD.dir}/\${match[1]}.webp\`;
}
`;
}

async function writePreview(page, results, dir) {
  mkdirSync(dir, { recursive: true });
  const figures = results
    .map((r) => `<figure><img src="data:image/webp;base64,${r.webp.toString("base64")}"><figcaption>${r.slug} ${r.error.toFixed(1)}</figcaption></figure>`)
    .join("");
  await page.setViewportSize({ width: 1400, height: 900 });
  await page.setContent(`<!doctype html><style>body{margin:12px;background:#221c33;display:flex;flex-wrap:wrap;gap:10px;font:11px system-ui;color:#eee}
    figure{margin:0;text-align:center}img{display:block;width:128px;height:128px;background:#2f2745}</style>${figures}`);
  await page.screenshot({ path: join(dir, "relic-icons-hd.png"), fullPage: true });
}

async function main() {
  const pck = openPck(pckPathFromArgs());
  const matches = matchShippedIcons(relicCatalog(pck).relics);
  const workDir = mkdtempSync(join(tmpdir(), "relic-hd-"));
  const browser = await chromium.launch();
  const results = [];
  const skipped = [];
  try {
    const page = await browser.newPage();
    for (const { shipped, relic } of matches) {
      if (!relic?.icon) {
        skipped.push(`${shipped.padEnd(24)} no ${HD.size}px icon in the game (${relic ? "atlas sprite only" : "not in the relic catalog"})`);
        continue;
      }
      const image = loadImage(pck, relic.icon);
      if (!image) {
        skipped.push(`${shipped.padEnd(24)} ${relic.icon} has no readable texture`);
        continue;
      }
      const gameUrl = await imageDataUrl(page, image);
      const smallUrl = `data:image/webp;base64,${readFileSync(join(RELIC_DIR, `${shipped}.webp`)).toString("base64")}`;
      const out = await page.evaluate(renderInPage, { gameUrl, smallUrl, ...HD });
      if (out.width !== HD.size || out.height !== HD.size) {
        skipped.push(`${shipped.padEnd(24)} game icon is ${out.width}x${out.height}, not ${HD.size}px`);
        continue;
      }
      if (out.error > SAME_ART_MAX_ERROR) {
        skipped.push(`${shipped.padEnd(24)} art differs from the shipped icon (error ${out.error.toFixed(1)})`);
        continue;
      }
      const webp = encodeWebp(Buffer.from(out.png, "base64"), workDir, shipped);
      results.push({ slug: shipped, error: out.error, webp });
    }
    const previewDir = arg("preview", "");
    if (previewDir) await writePreview(page, results, previewDir);
  } finally {
    await browser.close();
    pck.close();
    rmSync(workDir, { recursive: true, force: true });
  }

  const errors = results.map((r) => r.error).sort((a, b) => a - b);
  const kb = results.reduce((sum, r) => sum + r.webp.length, 0) / 1024;
  process.stdout.write(`${results.length} large icons (${kb.toFixed(0)} KB, median error ${errors[Math.floor(errors.length / 2)]?.toFixed(1)}, max ${errors.at(-1)?.toFixed(1)})\n`);
  if (skipped.length) process.stdout.write(`${skipped.length} without a large icon:\n  ${skipped.join("\n  ")}\n`);
  if (flag("dry")) return;

  rmSync(HD_DIR, { recursive: true, force: true });
  mkdirSync(HD_DIR, { recursive: true });
  for (const r of results) writeFileSync(join(HD_DIR, `${r.slug}.webp`), r.webp);
  writeFileSync(MODULE_FILE, moduleSource(results.map((r) => r.slug).sort()));
  process.stdout.write(`wrote ${HD_DIR_NAME}/ and lib/ui/relic-art-hd.js\n`);
}

main().catch((error) => {
  process.stderr.write(`${error instanceof Error ? error.stack : String(error)}\n`);
  process.exit(1);
});
