#!/usr/bin/env node
/**
 * Builds the header stage's painted props (the tower and the torches) for the
 * new look, from the masters in scripts/stage-art/props/:
 *
 *   tower.webp  the spire: a door, ten window slits and a brazier at the tip.
 *               Its door lights at A0, a window per level A1–A10, and the
 *               brazier becomes a beacon at A10 (Web/lib/ui/stage.js).
 *   torch.webp  a cold standing torch: every run in the last ten is one.
 *   flame.webp  the flame a won run's torch (and the A10 beacon) carries.
 *
 * Each master is cropped to the art (the boxes below were measured on the
 * masters, in master pixels) and written once at about twice the largest size
 * the header draws it, so it stays sharp on a 2x screen:
 *
 *   Web/assets/stage/props/<id>-v<version>.webp
 *   Web/lib/ui/stage-props.js   sizes, plus the tower's door, windows and
 *                               brazier as fractions of the built picture
 *
 * The masters were generated with GPT Image 2.6 (Higgsfield), 2:3, 2k,
 * transparent background; prompts in scripts/stage-art/README.md.
 *
 *   node scripts/build-stage-props.mjs
 *
 * Needs `cwebp` (Homebrew: brew install webp). Bump a prop's `version` when
 * its master or crop changes: /assets is cached as immutable.
 */

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const MASTERS = join(REPO_ROOT, "scripts", "stage-art", "props");
const OUT_DIR = join(REPO_ROOT, "Web", "assets", "stage", "props");
const MODULE = join(REPO_ROOT, "Web", "lib", "ui", "stage-props.js");

/**
 * crop: the art's box in the master (x, y, w, h). height: built picture
 * height in px. Tower geometry is in crop fractions (0–1), measured on the
 * master: x/y are centres, w/h sizes.
 */
const PROPS = Object.freeze([
  {
    id: "tower",
    version: 1,
    crop: [354, 19, 652, 2018],
    height: 760,
    geometry: {
      // The arched wooden door at the foot.
      door: { x: 0.503, y: 0.9604, w: 0.155, h: 0.0709 },
      // The ten window slits, bottom (A1) to top (A10): three in the lowest
      // tier, four in the middle one, three under the roof.
      windows: [0.8781, 0.8216, 0.7607, 0.6814, 0.6204, 0.5575, 0.495, 0.4172, 0.3548, 0.2929],
      window: { x: 0.5, w: 0.0521, h: 0.0401 },
      // The iron brazier bowl on the roof's tip.
      brazier: { x: 0.5, y: 0.0104, w: 0.213 },
    },
  },
  {
    id: "torch",
    version: 2,
    crop: [462, 147, 422, 1812],
    // Tall enough for the marching row on a wide header (up to 70px) at 2x.
    height: 176,
    geometry: {
      // The burnt head runs from the top to the cup's rim at 0.21; a flame
      // sits on it with its base here, so the lower wrapping still shows.
      flameBase: 0.14,
    },
  },
  {
    id: "flame",
    version: 1,
    crop: [133, 72, 1077, 1877],
    height: 112,
  },
]);

function fail(message) {
  process.stderr.write(`build-stage-props: ${message}\n`);
  process.exit(1);
}

function pixelSize(path) {
  const out = execFileSync("sips", ["-g", "pixelWidth", "-g", "pixelHeight", path], { encoding: "utf8" });
  const width = Number(/pixelWidth: (\d+)/.exec(out)?.[1]);
  const height = Number(/pixelHeight: (\d+)/.exec(out)?.[1]);
  if (!width || !height) fail(`could not read the size of ${path}`);
  return { width, height };
}

/** @param {{ id: string, version: number, crop: number[], height: number }} prop */
function buildProp(prop) {
  const master = join(MASTERS, `${prop.id}.webp`);
  if (!existsSync(master)) fail(`missing master ${master}`);
  const size = pixelSize(master);
  const [x, y, w, h] = prop.crop;
  if (x < 0 || y < 0 || x + w > size.width || y + h > size.height) fail(`${prop.id}: crop ${prop.crop} is outside the ${size.width}x${size.height} master`);
  const file = `${prop.id}-v${prop.version}.webp`;
  const out = join(OUT_DIR, file);
  execFileSync("cwebp", [
    "-quiet", "-q", "90", "-alpha_q", "100", "-exact", "-m", "6", "-sharp_yuv",
    "-crop", String(x), String(y), String(w), String(h),
    "-resize", "0", String(prop.height),
    master, "-o", out,
  ]);
  const built = pixelSize(out);
  return { id: prop.id, src: `/assets/stage/props/${file}`, width: built.width, height: built.height, geometry: prop.geometry || null };
}

function moduleSource(built) {
  const entries = built.map((p) => {
    const geometry = Object.entries(p.geometry || {}).map(([key, value]) => `, ${key}: ${JSON.stringify(value).replace(/"(\w+)":/g, "$1: ").replace(/,/g, ", ")}`).join("");
    return `  ${p.id}: Object.freeze({ src: ${JSON.stringify(p.src)}, width: ${p.width}, height: ${p.height}${geometry} }),`;
  });
  return `// GENERATED by scripts/build-stage-props.mjs — do not edit by hand.
//
// The header stage's painted props: the tower (door, ten windows, brazier as
// fractions of the picture: x/y centres, w/h sizes) and the torch and flame
// the last ten runs are drawn with.

export const STAGE_PROPS = Object.freeze({
${entries.join("\n")}
});
`;
}

function main() {
  mkdirSync(OUT_DIR, { recursive: true });
  const built = PROPS.map(buildProp);
  writeFileSync(MODULE, moduleSource(built));
  for (const p of built) process.stdout.write(`  ${p.src}  ${p.width}x${p.height}\n`);
  process.stdout.write(`  ${MODULE.replace(`${REPO_ROOT}/`, "")}\n`);
}

main();
