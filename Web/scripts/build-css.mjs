#!/usr/bin/env node
/**
 * Builds Web/styles.next.css from the small source files in Web/styles/src/.
 *
 * There is deliberately no bundler in this project. This is the one concat
 * step, and it exists for two reasons:
 *
 *   1. One render-blocking request and one `?v=` token instead of a dozen.
 *   2. Every source file is wrapped in its cascade layer here, in one place,
 *      so a new rule cannot accidentally be authored unlayered — an unlayered
 *      rule would outrank the whole legacy stylesheet AND every other new
 *      layer, which is how specificity wars start.
 *
 * Layer names are flat on purpose. Dotted names (`v.base`) would nest under a
 * single parent layer `v`, and the parent is ordered at its first mention —
 * which would put every new layer *before* `legacy` and hand the cascade back
 * to the old stylesheet.
 *
 * Run:    node Web/scripts/build-css.mjs
 * Check:  node Web/scripts/build-css.mjs --check   (fails if the committed
 *         output is stale; wired into `make preflight`)
 */

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const WEB_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC_ROOT = join(WEB_ROOT, "styles", "src");
const OUT_FILE = join(WEB_ROOT, "styles.next.css");

/** Cascade order, lowest priority first. `legacy` is Web/styles.css. */
export const LAYER_ORDER = [
  "v-override",
  "legacy",
  "v-reset",
  "v-tokens",
  "v-base",
  "v-shell",
  "v-components",
  "v-surfaces",
  "v-host",
  "v-util",
];

/**
 * Build manifest: [layer | null, path relative to styles/src].
 * `null` means "emit unlayered" and is reserved for at-rules that are not
 * subject to layering anyway (@font-face).
 */
const MANIFEST = [
  [null, "base/fonts.css"],
  ["v-override", "override/override.css"],
  ["v-reset", "reset/ledger.css"],
  ["v-tokens", "tokens/tokens.css"],
  ["v-tokens", "tokens/themes.css"],
  ["v-tokens", "bridge/legacy-tokens.css"],
  ["v-base", "base/base.css"],
  ["v-shell", "shell/shell.css"],
  ["v-shell", "shell/panel-head.css"],
  ["v-shell", "shell/mobile-nav.css"],
  ["v-components", "components/controls.css"],
  ["v-components", "components/filters.css"],
  ["v-components", "components/stage.css"],
  ["v-components", "components/stage-scenes.css"],
  ["v-components", "components/stage-life.css"],
  ["v-components", "components/stage-life-events.css"],
  ["v-components", "components/cards.css"],
  ["v-components", "components/charts.css"],
  ["v-components", "components/theme-picker.css"],
  ["v-components", "components/look-switch.css"],
  ["v-components", "components/milestone.css"],
  ["v-components", "components/tab-lock.css"],
  ["v-surfaces", "surfaces/overview.css"],
  ["v-surfaces", "surfaces/overview-grid.css"],
  ["v-surfaces", "surfaces/overview-widgets.css"],
  ["v-surfaces", "surfaces/overview-showcase.css"],
  ["v-surfaces", "surfaces/overview-arrange.css"],
  ["v-surfaces", "surfaces/overview-tour.css"],
  ["v-surfaces", "surfaces/empty.css"],
  ["v-surfaces", "surfaces/characters.css"],
  ["v-surfaces", "surfaces/ascensions.css"],
  ["v-surfaces", "surfaces/relics.css"],
  ["v-surfaces", "surfaces/cards.css"],
  ["v-surfaces", "surfaces/runs.css"],
  ["v-surfaces", "surfaces/runs-calendar.css"],
  ["v-surfaces", "surfaces/coop.css"],
  ["v-surfaces", "surfaces/community.css"],
  ["v-surfaces", "surfaces/settings.css"],
  ["v-host", "host/desktop.css"],
  ["v-util", "util/util.css"],
];

/** Strips comments and blank lines; keeps one declaration per line. */
function compact(css) {
  return css
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .split("\n")
    .map((line) => line.trimEnd())
    .filter((line) => line.trim() !== "")
    .join("\n");
}

function indent(css) {
  return css
    .split("\n")
    .map((line) => `  ${line}`)
    .join("\n");
}

export function build() {
  const parts = [
    "/* GENERATED by scripts/build-css.mjs from styles/src/ — do not edit. */",
    `@layer ${LAYER_ORDER.join(", ")};`,
  ];
  for (const [layer, rel] of MANIFEST) {
    const file = join(SRC_ROOT, rel);
    if (!existsSync(file)) {
      throw new Error(`build-css: manifest entry is missing on disk: styles/src/${rel}`);
    }
    const body = compact(readFileSync(file, "utf8"));
    if (!body) continue;
    parts.push(`/* ${rel} */`);
    parts.push(layer ? `@layer ${layer} {\n${indent(body)}\n}` : body);
  }
  return `${parts.join("\n")}\n`;
}

function main() {
  const check = process.argv.includes("--check");
  let output;
  try {
    output = build();
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    process.exit(1);
  }
  if (check) {
    // index.html declares the same layer order inline (it has to: the order
    // must be established before the legacy sheet is imported). If the two
    // drift, new CSS silently changes priority relative to legacy.
    const html = readFileSync(join(WEB_ROOT, "index.html"), "utf8");
    if (!html.includes(`@layer ${LAYER_ORDER.join(", ")};`)) {
      process.stderr.write(
        "index.html's inline @layer statement does not match LAYER_ORDER in scripts/build-css.mjs.\n"
      );
      process.exit(1);
    }
    const current = existsSync(OUT_FILE) ? readFileSync(OUT_FILE, "utf8") : "";
    if (current !== output) {
      process.stderr.write(
        "styles.next.css is stale. Run `make css` (node scripts/build-css.mjs) and commit the result.\n"
      );
      process.exit(1);
    }
    process.stdout.write("styles.next.css is up to date.\n");
    return;
  }
  writeFileSync(OUT_FILE, output);
  process.stdout.write(`styles.next.css written (${(output.length / 1024).toFixed(1)} KB raw).\n`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
